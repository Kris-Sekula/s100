#pragma once

/* Minimal embedded web UI, served from GET /.
 * Talks to /api/status, /api/library, /api/select, /api/eject,
 * /api/reinsert, /api/force, /api/power, /api/upload (raw-body
 * POST, ?name=<file>).
 *
 * v15 whole-card notes: the library list is the card snapshot from
 * the last local window. Since v37 uploads are only possible
 * while the drive is ejected (they stream straight to the card,
 * any size); the Upload button greys out otherwise.
 * v39: refusals and failures are shown (status "error" field and
 * HTTP error bodies), a queued swap held back by USB activity offers
 * "Force now", and the selected radio button follows the current
 * image (including Gotek-side changes). */
static const char FF_WEB_UI_HTML[] =
"<!doctype html><html><head><meta charset=\"utf-8\">\n"
"<title>FlashFloppy</title></head><body>\n"
"<h1>FlashFloppy</h1>\n"
"<p id=\"status\">Loading…</p>\n"
"<p id=\"err\" style=\"color:#b00;display:none\"></p>\n"
"<p id=\"wait\" style=\"display:none\">Waiting for the drive to go quiet before swapping…\n"
" <button onclick=\"forceSwap()\">Force now</button>\n"
" <small>(only if you are sure nothing is being written to the disk)</small></p>\n"
"<p><button id=\"reinsert\" onclick=\"reinsert()\">Re-insert card</button>\n"
"<button onclick=\"eject()\">Eject</button></p>\n"
"<div id=\"power\" style=\"display:none\">\n"
"<h2>Machine power</h2>\n"
"<p id=\"powerState\">-</p>\n"
"<p id=\"powerErr\" style=\"color:#b00;display:none\"></p>\n"
"<p><button onclick=\"powerAct('on')\">Power on</button>\n"
"<button onclick=\"powerAct('off')\">Power off</button>\n"
"<button onclick=\"powerAct('restart')\">Restart</button></p>\n"
"</div>\n"
"<h2>Library</h2><ul id=\"lib\"></ul>\n"
"<p><button onclick=\"selectChosen()\">Select</button>\n"
"<label><input type=\"checkbox\" id=\"rstAfter\"> restart machine after swap</label></p>\n"
"<h3>Config Files</h3><ul id=\"cfg\"></ul>\n"
"<h2>Upload</h2>\n"
"<input type=\"file\" id=\"file\">\n"
"<button id=\"upBtn\" onclick=\"upload()\">Upload</button>\n"
"<span id=\"upMsg\"></span>\n"
"<p><progress id=\"upBar\" max=\"100\" value=\"0\" style=\"display:none;width:60%\"></progress></p>\n"
"<p id=\"upHint\">Uploads write straight to the card, any size — but only while the drive is ejected.</p>\n"
"<script>\n"
"let lastLib='', cur='', lastCur=null, pwrFile=false, actionErr='';\n"
"function fmtSize(n){\n"
"  if(n<1000) return n+' B';\n"
"  let v,u;\n"
"  if(n>=999500000){ v=n/1e9; u='G'; }\n"
"  else if(n>=999500){ v=n/1e6; u='M'; }\n"
"  else { v=n/1e3; u='k'; }\n"
"  let s=v>=100?String(Math.round(v)):v>=10?v.toFixed(1):v.toFixed(2);\n"
"  if(s.indexOf('.')>0) s=s.replace(/0+$/,'').replace(/\\.$/,'');\n"
"  return s+u;\n"
"}\n"
"function show(id,txt){\n"
"  const e=document.getElementById(id);\n"
"  e.textContent=txt||''; e.style.display=txt?'':'none';\n"
"}\n"
"/* POST and report a refusal (409 busy, 400 bad name, ...) instead of\n"
"   silently ignoring it (v39). */\n"
"async function post(url,body){\n"
"  try{\n"
"    const opt={method:'POST'};\n"
"    if(body!==undefined){\n"
"      opt.headers={'Content-Type':'application/json'};\n"
"      opt.body=JSON.stringify(body);\n"
"    }\n"
"    const r=await fetch(url,opt);\n"
"    if(!r.ok){\n"
"      actionErr=(await r.text())||('HTTP '+r.status);\n"
"      show('err',actionErr);\n"
"      setTimeout(()=>{ actionErr=''; },8000);\n"
"      return false;\n"
"    }\n"
"    actionErr='';\n"
"    return true;\n"
"  }catch(e){\n"
"    actionErr='No answer from the device';\n"
"    show('err',actionErr);\n"
"    return false;\n"
"  }\n"
"}\n"
"async function refresh(){\n"
"  let s;\n"
"  try{\n"
"    s=await (await fetch('/api/status',{cache:'no-store'})).json();\n"
"  }catch(e){\n"
"    document.getElementById('status').textContent='Device not reachable';\n"
"    return;\n"
"  }\n"
"  cur=s.current||'';\n"
"  document.getElementById('status').textContent=\n"
"    'Presented: '+(s.current||'(none)')+' | state: '+s.state+\n"
"    ' | '+(s.uploading?'upload in progress':\n"
"      (s.ejected?'drive ejected':'drive presented'))+\n"
"    ' | wifi: '+(s.wifi||'-');\n"
"  show('err',s.error||actionErr);\n"
"  document.getElementById('wait').style.display=s.waiting_usb?'':'none';\n"
"  const canUp=!!s.ejected&&!s.uploading;\n"
"  document.getElementById('upBtn').disabled=!canUp;\n"
"  document.getElementById('file').disabled=!canUp;\n"
"  document.getElementById('upHint').textContent=s.uploading?\n"
"    'Upload in progress…':s.ejected?\n"
"    'Drive is ejected: the file will be written directly to '\n"
"      +'the card. Re-insert when you are done uploading.':\n"
"    'Eject the drive first — uploads are only possible while '\n"
"      +'it is ejected (they write straight to the card).';\n"
"  let libTxt='';\n"
"  try{\n"
"    libTxt=await (await fetch('/api/library',{cache:'no-store'})).text();\n"
"  }catch(e){ return; }\n"
"  if(libTxt!==lastLib){ lastLib=libTxt; lastCur=null;\n"
"    const lib=JSON.parse(libTxt);\n"
"    pwrFile=lib.files.some(f=>f.kind==='config'&&\n"
"      f.name.toUpperCase()==='POWER.CFG');\n"
"    const ul=document.getElementById('lib'); ul.innerHTML='';\n"
"    const cfgUl=document.getElementById('cfg'); cfgUl.innerHTML='';\n"
"    lib.files.forEach(f=>{\n"
"      const li=document.createElement('li');\n"
"      if(f.kind==='image'){\n"
"        const lab=document.createElement('label');\n"
"        const r=document.createElement('input');\n"
"        r.type='radio'; r.name='sel'; r.value=f.path;\n"
"        lab.appendChild(r);\n"
"        lab.appendChild(document.createTextNode(\n"
"          ' '+f.name+' ('+fmtSize(f.size)+')'));\n"
"        li.appendChild(lab);\n"
"      } else {\n"
"        li.textContent=f.name+' ('+fmtSize(f.size)+')'+\n"
"          (f.kind==='backup'?' [backup]':'');\n"
"      }\n"
"      (f.kind==='config'?cfgUl:ul).appendChild(li);});\n"
"  }\n"
"  /* Follow the current image — including a change made on the\n"
"     Gotek's own buttons — but only when it actually changes, so a\n"
"     choice the user is about to Select is not reset (v39). */\n"
"  if(cur!==lastCur){ lastCur=cur;\n"
"    document.querySelectorAll('input[name=sel]').forEach(r=>{\n"
"      r.checked=(r.value===cur);});\n"
"  }\n"
"  try{\n"
"    const pw=await (await fetch('/api/power',{cache:'no-store'})).json();\n"
"    const pdiv=document.getElementById('power');\n"
"    if(pw.configured&&pwrFile){ pdiv.style.display='';\n"
"      document.getElementById('powerState').textContent=\n"
"        (pw.name||'Machine')+': '+(pw.restarting?'restarting...':\n"
"          pw.busy?'working...':pw.reachable?(pw.on?\n"
"            ('ON · '+(pw.watts||0).toFixed(1)+' W'):'OFF'):\n"
"          'unreachable');\n"
"      show('powerErr',pw.error);\n"
"    } else { pdiv.style.display='none'; }\n"
"  }catch(e){}\n"
"}\n"
"async function selectChosen(){\n"
"  const r=document.querySelector('input[name=sel]:checked');\n"
"  if(!r) return;\n"
"  await post('/api/select',{path:r.value,\n"
"    restart:document.getElementById('rstAfter').checked});\n"
"  watchState();}\n"
"async function forceSwap(){\n"
"  if(!confirm('Swap now even though the drive is busy? '+\n"
"    'Anything being written to the disk image right now may be lost.'))\n"
"    return;\n"
"  await post('/api/force'); watchState();}\n"
"async function powerAct(a){\n"
"  if(a==='off'&&!confirm('Switch the machine off?')) return;\n"
"  await post('/api/power',{action:a});\n"
"  setTimeout(refresh,400);}\n"
"async function reinsert(){ await post('/api/reinsert'); watchState();}\n"
"async function eject(){ await post('/api/eject'); watchState();}\n"
"function watchState(){\n"
"  refresh();\n"
"  let n=0;\n"
"  const t=setInterval(()=>{ refresh(); if(++n>=40) clearInterval(t); },300);\n"
"}\n"
"function upload(){\n"
"  const inp=document.getElementById('file');\n"
"  const f=inp.files[0];\n"
"  if(!f) return;\n"
"  const bar=document.getElementById('upBar');\n"
"  const msg=document.getElementById('upMsg');\n"
"  bar.style.display=''; bar.value=0;\n"
"  msg.textContent='Uploading… 0%';\n"
"  const xhr=new XMLHttpRequest();\n"
"  xhr.open('POST','/api/upload?name='+encodeURIComponent(f.name));\n"
"  xhr.upload.onprogress=e=>{\n"
"    if(e.lengthComputable){\n"
"      const pc=Math.round(e.loaded/e.total*100);\n"
"      bar.value=pc;\n"
"      msg.textContent='Uploading… '+pc+'% ('+\n"
"        fmtSize(e.loaded)+' of '+fmtSize(f.size)+')';\n"
"    }};\n"
"  xhr.onload=()=>{\n"
"    bar.style.display='none';\n"
"    if(xhr.status>=200&&xhr.status<300){\n"
"      inp.value='';\n"
"      let rb=false;\n"
"      try{ rb=JSON.parse(xhr.responseText).reboot_needed; }catch(e){}\n"
"      msg.textContent=rb?'Done — power-cycle the dongle to apply this '\n"
"        +'config file':'Done';\n"
"    } else {\n"
"      msg.textContent='Failed: '+(xhr.responseText||xhr.status);\n"
"    }\n"
"    refresh();\n"
"  };\n"
"  xhr.onerror=()=>{\n"
"    bar.style.display='none';\n"
"    msg.textContent='Failed (connection lost)';\n"
"  };\n"
"  xhr.send(f);\n"
"}\n"
"refresh();\n"
"setInterval(refresh,2000);\n"
"</script></body></html>\n";

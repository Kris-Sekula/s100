#pragma once

/* Minimal embedded web UI, served from GET /.
 * Talks to /api/status, /api/library, /api/select, /api/eject,
 * /api/reinsert, /api/upload (raw-body POST, ?name=<file>).
 *
 * v15 whole-card notes: the library list is the card snapshot from
 * the last local window; uploads are staged in RAM and written to
 * the card when a window runs (Select, Re-insert, or Eject). */
static const char FF_WEB_UI_HTML[] =
"<!doctype html><html><head><meta charset=\"utf-8\">"
"<title>FlashFloppy</title></head><body>"
"<h1>FlashFloppy</h1>"
"<p id=\"status\">Loading…</p>"
"<p><button id=\"reinsert\" onclick=\"reinsert()\">"
"Re-insert card (apply uploads)</button> "
"<button onclick=\"eject()\">Eject</button></p>"
"<h2>Library</h2><ul id=\"lib\"></ul>"
"<p><button onclick=\"selectChosen()\">Select</button></p>"
"<h2>Upload</h2>"
"<input type=\"file\" id=\"file\">"
"<button onclick=\"upload()\">Upload</button>"
"<p>Uploads are staged and written to the card on the next "
"re-insert, select, or eject.</p>"
"<script>"
"let lastLib='', cur='';"
"async function refresh(){"
"  const s=await (await fetch('/api/status',{cache:'no-store'})).json();"
"  cur=s.current||'';"
"  document.getElementById('status').textContent="
"    'Presented: '+(s.current||'(none)')+' | state: '+s.state+"
"    ' | staged: '+s.staged+' | wifi: '+(s.wifi||'-');"
"  const libTxt=await (await fetch('/api/library',"
"    {cache:'no-store'})).text();"
"  if(libTxt===lastLib) return; lastLib=libTxt;"
"  const lib=JSON.parse(libTxt);"
"  const ul=document.getElementById('lib'); ul.innerHTML='';"
"  lib.files.forEach(f=>{"
"    const li=document.createElement('li');"
"    if(f.kind==='image'){"
"      const lab=document.createElement('label');"
"      const r=document.createElement('input');"
"      r.type='radio'; r.name='sel'; r.value=f.path;"
"      if(f.path===cur) r.checked=true;"
"      lab.appendChild(r);"
"      lab.appendChild(document.createTextNode("
"        ' '+f.name+' ('+f.size+')'));"
"      li.appendChild(lab);"
"    } else {"
"      li.textContent=f.name+' ('+f.size+') ';"
"      if(f.kind==='config'){"
"        li.textContent+='[config]';"
"      } else if(f.kind==='backup'){"
"        li.textContent+='[backup]';"
"      } else if(f.kind==='staged'){"
"        li.textContent+='[staged - not on card yet]';"
"      }"
"    }"
"    ul.appendChild(li);});}"
"async function selectChosen(){"
"  const r=document.querySelector('input[name=sel]:checked');"
"  if(!r) return;"
"  await fetch('/api/select',{method:'POST',"
"    headers:{'Content-Type':'application/json'},"
"    body:JSON.stringify({path:r.value})}); refresh();}"
"async function reinsert(){"
"  await fetch('/api/reinsert',{method:'POST'}); refresh();}"
"async function eject(){"
"  await fetch('/api/eject',{method:'POST'}); refresh();}"
"async function upload(){"
"  const f=document.getElementById('file').files[0];"
"  if(!f) return;"
"  await fetch('/api/upload?name='+encodeURIComponent(f.name),"
"    {method:'POST',body:f}); refresh();}"
"refresh();"
"setInterval(refresh,2000);"
"</script></body></html>";

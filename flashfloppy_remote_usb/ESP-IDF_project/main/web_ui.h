#pragma once

/* Minimal embedded web UI, served from GET /.
 * Talks to /api/status, /api/library, /api/select, /api/eject,
 * /api/reinsert, /api/upload (raw-body POST, ?name=<file>).
 *
 * v15 whole-card notes: the library list is the card snapshot from
 * the last local window. Since v37 uploads are only possible
 * while the drive is ejected (they stream straight to the card,
 * any size); the Upload button greys out otherwise. */
static const char FF_WEB_UI_HTML[] =
"<!doctype html><html><head><meta charset=\"utf-8\">"
"<title>FlashFloppy</title></head><body>"
"<h1>FlashFloppy</h1>"
"<p id=\"status\">Loading…</p>"
"<p><button id=\"reinsert\" onclick=\"reinsert()\">"
"Re-insert card</button> "
"<button onclick=\"eject()\">Eject</button></p>"
"<div id=\"power\" style=\"display:none\">"
"<h2>Machine power</h2>"
"<p id=\"powerState\">-</p>"
"<p><button onclick=\"powerAct('on')\">Power on</button> "
"<button onclick=\"powerAct('off')\">Power off</button> "
"<button onclick=\"powerAct('restart')\">Restart</button></p>"
"</div>"
"<h2>Library</h2><ul id=\"lib\"></ul>"
"<p><button onclick=\"selectChosen()\">Select</button> "
"<label><input type=\"checkbox\" id=\"rstAfter\"> "
"restart machine after swap</label></p>"
"<h3>Config Files</h3><ul id=\"cfg\"></ul>"
"<h2>Upload</h2>"
"<input type=\"file\" id=\"file\">"
"<button id=\"upBtn\" onclick=\"upload()\">Upload</button> "
"<span id=\"upMsg\"></span>"
"<p><progress id=\"upBar\" max=\"100\" value=\"0\" "
"style=\"display:none;width:60%\"></progress></p>"
"<p id=\"upHint\">Uploads write straight to the card, any size "
"— but only while the drive is ejected.</p>"
"<script>"
"let lastLib='', cur='', pwrFile=false;"
"function fmtSize(n){"
"  if(n<1000) return n+' B';"
"  let v,u;"
"  if(n>=999500000){ v=n/1e9; u='G'; }"
"  else if(n>=999500){ v=n/1e6; u='M'; }"
"  else { v=n/1e3; u='k'; }"
"  let s=v>=100?String(Math.round(v)):"
"    v>=10?v.toFixed(1):v.toFixed(2);"
"  if(s.indexOf('.')>0)"
"    s=s.replace(/0+$/,'').replace(/\\.$/,'');"
"  return s+u;"
"}"
"async function refresh(){"
"  const s=await (await fetch('/api/status',{cache:'no-store'})).json();"
"  cur=s.current||'';"
"  document.getElementById('status').textContent="
"    'Presented: '+(s.current||'(none)')+' | state: '+s.state+"
"    ' | '+(s.uploading?'upload in progress':"
"      (s.ejected?'drive ejected':'drive presented'))+"
"    ' | wifi: '+(s.wifi||'-');"
"  const canUp=!!s.ejected&&!s.uploading;"
"  document.getElementById('upBtn').disabled=!canUp;"
"  document.getElementById('file').disabled=!canUp;"
"  document.getElementById('upHint').textContent=s.uploading?"
"    'Upload in progress…':s.ejected?"
"    'Drive is ejected: the file will be written directly to '"
"      +'the card. Re-insert when you are done uploading.':"
"    'Eject the drive first — uploads are only possible while '"
"      +'it is ejected (they write straight to the card).';"
"  const libTxt=await (await fetch('/api/library',"
"    {cache:'no-store'})).text();"
"  if(libTxt!==lastLib){ lastLib=libTxt;"
"  const lib=JSON.parse(libTxt);"
"  pwrFile=lib.files.some(f=>f.kind==='config'&&"
"    f.name.toUpperCase()==='POWER.CFG');"
"  const ul=document.getElementById('lib'); ul.innerHTML='';"
"  const cfgUl=document.getElementById('cfg');"
"  cfgUl.innerHTML='';"
"  lib.files.forEach(f=>{"
"    const li=document.createElement('li');"
"    if(f.kind==='image'){"
"      const lab=document.createElement('label');"
"      const r=document.createElement('input');"
"      r.type='radio'; r.name='sel'; r.value=f.path;"
"      if(f.path===cur) r.checked=true;"
"      lab.appendChild(r);"
"      lab.appendChild(document.createTextNode("
"        ' '+f.name+' ('+fmtSize(f.size)+')'));"
"      li.appendChild(lab);"
"    } else {"
"      li.textContent=f.name+' ('+fmtSize(f.size)+') ';"
"      if(f.kind==='backup'){"
"        li.textContent+='[backup]';"
"      }"
"    }"
"    (f.kind==='config'?cfgUl:ul).appendChild(li);});"
"  }"
"  try{"
"    const pw=await (await fetch('/api/power',"
"      {cache:'no-store'})).json();"
"    const pdiv=document.getElementById('power');"
"    if(pw.configured&&pwrFile){ pdiv.style.display='';"
"      document.getElementById('powerState').textContent="
"        (pw.name||'Machine')+': '+(pw.restarting?"
"          'restarting...':pw.reachable?(pw.on?"
"            ('ON · '+(pw.watts||0).toFixed(1)+' W'):'OFF'):"
"          'unreachable');"
"    } else { pdiv.style.display='none'; }"
"  }catch(e){}"
"}"
"async function selectChosen(){"
"  const r=document.querySelector('input[name=sel]:checked');"
"  if(!r) return;"
"  await fetch('/api/select',{method:'POST',"
"    headers:{'Content-Type':'application/json'},"
"    body:JSON.stringify({path:r.value,"
"      restart:document.getElementById('rstAfter').checked})});"
"  watchState();}"
"async function powerAct(a){"
"  await fetch('/api/power',{method:'POST',"
"    headers:{'Content-Type':'application/json'},"
"    body:JSON.stringify({action:a})});"
"  setTimeout(refresh,400);}"
"async function reinsert(){"
"  await fetch('/api/reinsert',{method:'POST'}); watchState();}"
"async function eject(){"
"  await fetch('/api/eject',{method:'POST'}); watchState();}"
"function watchState(){"
"  refresh();"
"  let n=0;"
"  const t=setInterval(()=>{ refresh();"
"    if(++n>=20) clearInterval(t); },300);"
"}"
"function upload(){"
"  const inp=document.getElementById('file');"
"  const f=inp.files[0];"
"  if(!f) return;"
"  const bar=document.getElementById('upBar');"
"  const msg=document.getElementById('upMsg');"
"  bar.style.display=''; bar.value=0;"
"  msg.textContent='Uploading… 0%';"
"  const xhr=new XMLHttpRequest();"
"  xhr.open('POST','/api/upload?name='+"
"    encodeURIComponent(f.name));"
"  xhr.upload.onprogress=e=>{"
"    if(e.lengthComputable){"
"      const pc=Math.round(e.loaded/e.total*100);"
"      bar.value=pc;"
"      msg.textContent='Uploading… '+pc+'% ('+"
"        fmtSize(e.loaded)+' of '+fmtSize(f.size)+')';"
"    }};"
"  xhr.onload=()=>{"
"    bar.style.display='none';"
"    if(xhr.status>=200&&xhr.status<300){"
"      inp.value='';"
"      msg.textContent='Done';"
"    } else {"
"      msg.textContent='Failed ('+xhr.status+')';"
"    }"
"    refresh();"
"  };"
"  xhr.onerror=()=>{"
"    bar.style.display='none';"
"    msg.textContent='Failed';"
"  };"
"  xhr.send(f);"
"}"
"refresh();"
"setInterval(refresh,2000);"
"</script></body></html>";
